function record = generate_prediction_calibration_demo(projectRoot, outputRoot, seed)
%GENERATE_PREDICTION_CALIBRATION_DEMO Synthetic prediction/calibration fixture.
% The output is a visualization test fixture only and is not contest evidence.
if nargin < 3
    seed = 20260801;
end
setup_modeling_path(projectRoot);
rng(seed, 'twister');

folder = fullfile(outputRoot, 'prediction-calibration');
if ~isfolder(folder), mkdir(folder); end
figProbe = figure('Visible', 'off');
style = applyModelingStyle(axes(figProbe), 'FontSize', 8.5);
close(figProbe);

n = 336;
trainN = 240;
t = (1:n).';
temperature = 19 + 5.5 * sin(2*pi*t/168) + 1.8 * cos(2*pi*t/24 + 0.4);
truth = 84 + 0.032*t + 7.2*sin(2*pi*t/24) + 2.5*cos(2*pi*t/168) ...
    + 0.10*(temperature - 19).^2;
noiseScale = 1.25 + 0.010*t;
observed = truth + noiseScale .* randn(n, 1);

features = [t/168, sin(2*pi*t/24), cos(2*pi*t/24), ...
    sin(2*pi*t/168), cos(2*pi*t/168), temperature, temperature.^2];
model = fitrensemble(features(1:trainN, :), observed(1:trainN), ...
    'Method', 'LSBoost', 'NumLearningCycles', 140, ...
    'Learners', 'tree', 'LearnRate', 0.055);
mainAll = predict(model, features);
baselineAll = nan(n, 1);
baselineAll(25:end) = observed(1:end-24);

trainResidual = observed(1:trainN) - mainAll(1:trainN);
residualQuantiles = quantile(trainResidual, [0.025, 0.975]);
testIndex = (trainN+1:n).';
mainTest = mainAll(testIndex);
baselineTest = baselineAll(testIndex);
observedTest = observed(testIndex);
lower95 = mainTest + residualQuantiles(1);
upper95 = mainTest + residualQuantiles(2);
mainResidual = observedTest - mainTest;
baselineResidual = observedTest - baselineTest;
rmseMain = sqrt(mean(mainResidual.^2));
rmseBaseline = sqrt(mean(baselineResidual.^2));
maeMain = mean(abs(mainResidual));
maeBaseline = mean(abs(baselineResidual));
r2Main = 1 - sum(mainResidual.^2) / sum((observedTest - mean(observedTest)).^2);
coverageMain = mean(observedTest >= lower95 & observedTest <= upper95);

horizonEdges = [1, 25, 49, 73, 97];
horizonLabel = ["1-24 h", "25-48 h", "49-72 h", "73-96 h"];
horizon = zeros(4, 1);
mainRmse = zeros(4, 1); baselineRmse = zeros(4, 1);
mainCoverage = zeros(4, 1); baselineCoverage = zeros(4, 1);
for k = 1:4
    local = horizonEdges(k):horizonEdges(k+1)-1;
    horizon(k) = k;
    mainRmse(k) = sqrt(mean(mainResidual(local).^2));
    baselineRmse(k) = sqrt(mean(baselineResidual(local).^2));
    mainCoverage(k) = mean(observedTest(local) >= lower95(local) & observedTest(local) <= upper95(local));
    baselineCoverage(k) = mean(abs(baselineResidual(local)) <= 1.96*std(trainResidual));
end

seriesTable = table(t, observed, truth, temperature, mainAll, baselineAll, ...
    [nan(trainN,1); lower95], [nan(trainN,1); upper95], ...
    [nan(trainN,1); mainResidual], [nan(trainN,1); baselineResidual], ...
    t > trainN, 'VariableNames', {'TimeHour','Observed','Truth','Temperature', ...
    'MainPrediction','BaselinePrediction','Lower95','Upper95', ...
    'MainResidual','BaselineResidual','IsTest'});
horizonTable = table(horizon, horizonLabel.', mainRmse, baselineRmse, ...
    mainCoverage, baselineCoverage, 'VariableNames', ...
    {'HorizonBlock','Horizon','MainRMSE','BaselineRMSE','MainCoverage','BaselineCoverage'});
writetable(seriesTable, fullfile(folder, 'prediction_series.csv'), 'Encoding', 'UTF-8');
writetable(horizonTable, fullfile(folder, 'horizon_metrics.csv'), 'Encoding', 'UTF-8');
save(fullfile(folder, 'source_data.mat'), 'seriesTable', 'horizonTable', ...
    'features', 'residualQuantiles', 'seed', '-v7');

fig = figure('Visible', 'off', 'Color', 'white', 'Units', 'centimeters', ...
    'Position', [2, 2, 15.8, 12.2]);
cleanup = onCleanup(@() close(fig)); %#ok<NASGU>
layout = tiledlayout(fig, 2, 2, 'TileSpacing', 'compact', 'Padding', 'compact');

ax = nexttile(layout); style = applyModelingStyle(ax, 'FontSize', 8.5); hold(ax, 'on');
patch(ax, [testIndex; flipud(testIndex)], [lower95; flipud(upper95)], ...
    style.palette.primary*0.16 + style.palette.background*0.84, ...
    'EdgeColor', 'none', 'HandleVisibility', 'off');
pObs = plot(ax, t(trainN-71:end), observed(trainN-71:end), '-', 'Color', style.textColor, ...
    'LineWidth', 1.05, 'DisplayName', '观测值');
pBase = plot(ax, testIndex, baselineTest, '--s', 'Color', style.palette.baseline, ...
    'LineWidth', style.lineWidth, 'MarkerSize', 3.3, 'MarkerIndices', 1:8:numel(testIndex), ...
    'MarkerFaceColor', 'white', 'DisplayName', '季节朴素基线');
pMain = plot(ax, testIndex, mainTest, '-o', 'Color', style.palette.primary, ...
    'LineWidth', style.lineWidth+0.15, 'MarkerSize', 3.3, 'MarkerIndices', 1:8:numel(testIndex), ...
    'MarkerFaceColor', 'white', 'DisplayName', '集成主模型');
xline(ax, trainN, ':', 'Color', style.palette.highlight, 'LineWidth', 1.1, ...
    'HandleVisibility', 'off');
hold(ax, 'off');
xlabel(ax, '时间（h）'); ylabel(ax, '系统负荷（MW）'); title(ax, '预测区间与测试段');
legend(ax, [pObs pBase pMain], 'Location', 'northwest', 'Box', 'off', 'FontSize', 7.3);
text(ax, 0.98, 0.06, sprintf('RMSE %.2f | 覆盖率 %.1f%%', rmseMain, 100*coverageMain), ...
    'Units', 'normalized', 'HorizontalAlignment', 'right', 'Color', style.palette.primary, ...
    'FontName', style.fontName, 'FontSize', 8);
mm_demo_panel_label(ax, '(a)', style);

ax = nexttile(layout); style = applyModelingStyle(ax, 'FontSize', 8.5); hold(ax, 'on');
scatter(ax, observedTest, baselineTest, 18, style.palette.baseline, 's', ...
    'LineWidth', 0.7, 'DisplayName', '季节朴素基线');
scatter(ax, observedTest, mainTest, 20, style.palette.primary, 'o', ...
    'LineWidth', 0.8, 'DisplayName', '集成主模型');
lims = [min([observedTest; mainTest; baselineTest])-2, max([observedTest; mainTest; baselineTest])+2];
plot(ax, lims, lims, ':', 'Color', style.palette.ink, 'LineWidth', 1.0, 'HandleVisibility', 'off');
xlim(ax, lims); ylim(ax, lims); axis(ax, 'square');
xlabel(ax, '观测负荷（MW）'); ylabel(ax, '预测负荷（MW）'); title(ax, '校准关系');
legend(ax, 'Location', 'northwest', 'Box', 'off', 'FontSize', 7.5);
text(ax, 0.05, 0.94, sprintf('主模型 R^2 = %.3f', r2Main), 'Units', 'normalized', ...
    'Color', style.palette.primary, 'FontName', style.fontName, 'FontSize', 8);
mm_demo_panel_label(ax, '(b)', style);

ax = nexttile(layout); style = applyModelingStyle(ax, 'FontSize', 8.5); hold(ax, 'on');
standardResidual = mainResidual / std(trainResidual);
outlier = abs(standardResidual) > 2;
scatter(ax, mainTest, standardResidual, 20, style.palette.primary, 'o', ...
    'MarkerFaceColor', 'white', 'DisplayName', '标准化残差');
scatter(ax, mainTest(outlier), standardResidual(outlier), 30, style.palette.risk, 'x', ...
    'LineWidth', 1.3, 'DisplayName', '|r| > 2');
smoothResidual = smoothdata(standardResidual, 'movmedian', 11);
plot(ax, mainTest, smoothResidual, '-', 'Color', style.palette.improved, ...
    'LineWidth', 1.3, 'DisplayName', '移动中位数');
yline(ax, 0, ':', 'Color', style.palette.ink, 'HandleVisibility', 'off');
yline(ax, [-2 2], '--', 'Color', style.palette.risk, 'LineWidth', 0.8, 'HandleVisibility', 'off');
xlabel(ax, '拟合负荷（MW）'); ylabel(ax, '标准化残差'); title(ax, '残差诊断');
legend(ax, 'Location', 'southoutside', 'NumColumns', 3, 'Box', 'off', 'FontSize', 7.3);
text(ax, 0.98, 0.94, sprintf('异常点 %d/%d', sum(outlier), numel(outlier)), ...
    'Units', 'normalized', 'HorizontalAlignment', 'right', 'Color', style.palette.risk, ...
    'FontName', style.fontName, 'FontSize', 8);
mm_demo_panel_label(ax, '(c)', style);

ax = nexttile(layout); style = applyModelingStyle(ax, 'FontSize', 8.5); hold(ax, 'on');
plot(ax, horizon, 100*mainCoverage, '-o', 'Color', style.palette.primary, ...
    'LineWidth', style.lineWidth, 'MarkerFaceColor', 'white', 'MarkerSize', 4.2, ...
    'DisplayName', '主模型覆盖率');
plot(ax, horizon, 100*baselineCoverage, '--s', 'Color', style.palette.baseline, ...
    'LineWidth', style.lineWidth, 'MarkerFaceColor', 'white', 'MarkerSize', 4.0, ...
    'DisplayName', '基线覆盖率');
yline(ax, 95, ':', 'Color', style.palette.highlight, 'LineWidth', 1.2, ...
    'DisplayName', '目标 95%');
xticks(ax, horizon); xticklabels(ax, horizonLabel);
xlabel(ax, '预测时域'); ylabel(ax, '区间覆盖率（%）'); title(ax, '覆盖率随时域变化');
ylim(ax, [70 102]); legend(ax, 'Location', 'southwest', 'Box', 'off', 'FontSize', 7.3);
mm_demo_panel_label(ax, '(d)', style);

basePath = fullfile(folder, 'prediction_calibration');
artifacts = exportModelingFigure(fig, basePath, 'Resolution', 400);
contract = struct('contract_version', '2.0', 'id', 'fixture-prediction-calibration', ...
    'question_id', 'DEMO', 'claim_id', 'fixture-prediction-calibration', ...
    'synthetic_fixture', true, 'contest_evidence_eligible', false, ...
    'core_conclusion', '工具验证：预测区间、校准、残差诊断和覆盖率可以在一张组合图中形成完整证据链。', ...
    'evidence_chain', {{'prediction_series.csv', 'horizon_metrics.csv'}}, ...
    'kind', 'data', 'archetype', 'prediction-interval-and-calibration', 'backend', 'matlab', ...
    'palette_id', 'journal-spectrum-v2', ...
    'color_encoding', {{'primary=主模型；baseline=灰色虚线方形；risk=异常残差叉号；highlight=95%目标线；线型和标记提供第二编码'}}, ...
    'source_data', {{'prediction_series.csv', 'horizon_metrics.csv', 'source_data.mat'}}, ...
    'source_script', 'matlab/demos/generate_prediction_calibration_demo.m', ...
    'outputs', struct('pdf', 'prediction_calibration.pdf', 'svg', 'prediction_calibration.svg', 'png', 'prediction_calibration.png', 'png_dpi', 400), ...
    'baseline', '季节朴素法 y(t)=y(t-24)', ...
    'axes', {{'时间（h）/系统负荷（MW）', '观测负荷（MW）/预测负荷（MW）', '拟合负荷（MW）/标准化残差', '预测时域/区间覆盖率（%）'}}, ...
    'caption', '合成负荷数据上的预测、校准、残差和覆盖率示例；阴影表示经验 95% 预测区间，数值仅用于工作台绘图验证。', ...
    'panel_map', {{'a: prediction interval', 'b: calibration', 'c: residual diagnosis', 'd: horizon coverage'}}, ...
    'statistics', {{'RMSE', 'MAE', 'R^2', 'empirical 95% interval', 'coverage by horizon'}}, ...
    'review_risks', {{'synthetic data only', 'interval uses training residual quantiles', 'not eligible for contest claims'}}, ...
    'final_width_mm', 158, 'min_font_pt', 8);
mm_demo_write_json(fullfile(folder, 'demo_contract.json'), contract);
summary = struct('seed', seed, 'train_observations', trainN, 'test_observations', n-trainN, ...
    'metrics', struct('main_rmse', rmseMain, 'baseline_rmse', rmseBaseline, ...
    'main_mae', maeMain, 'baseline_mae', maeBaseline, 'main_r2', r2Main, ...
    'main_coverage_95', coverageMain, 'residual_quantile_low', residualQuantiles(1), ...
    'residual_quantile_high', residualQuantiles(2)), ...
    'source_script', 'matlab/demos/generate_prediction_calibration_demo.m');
mm_demo_write_json(fullfile(folder, 'summary.json'), summary);
dataManifest = mm_demo_data_manifest(folder, {'prediction_series.csv', 'horizon_metrics.csv', 'demo_contract.json', 'summary.json'});
mm_demo_write_json(fullfile(folder, 'data_hashes.json'), dataManifest);
artifacts.csv = {'prediction_series.csv', 'horizon_metrics.csv'};
artifacts.mat = 'source_data.mat';
artifacts.contract = 'demo_contract.json';
artifacts.summary = 'summary.json';
record = struct('id', 'prediction-calibration', 'folder', folder, 'artifacts', artifacts, 'summary', summary);
end
