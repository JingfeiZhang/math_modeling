function style = applyModelingStyle(ax, varargin)
%APPLYMODELINGSTYLE Apply a compact, print-safe contest-paper chart style.

parser = inputParser;
addRequired(parser, 'ax');
addParameter(parser, 'FontName', 'Microsoft YaHei', @(x) ischar(x) || isstring(x));
addParameter(parser, 'FontSize', 9, @(x) isnumeric(x) && isscalar(x) && x > 0);
parse(parser, ax, varargin{:});

style = struct();
style.palette = struct( ...
    'primary', [0.32156863, 0.57254902, 0.96862745], ...
    'baseline', [0.47450980, 0.79215686, 0.98431373], ...
    'improved', [0.30588235, 0.65098039, 0.37647059], ...
    'highlight', [0.96862745, 0.63529412, 0.30980392], ...
    'risk', [0.91372549, 0.32549020, 0.31764706], ...
    'auxiliary', [0.66666667, 0.46666667, 0.91372549], ...
    'accent', [0.80000000, 0.14117647, 0.48627451], ...
    'caution', [0.98431373, 0.92156863, 0.40000000], ...
    'ink', [0.12156863, 0.16078431, 0.20000000], ...
    'grid', [0.85098039, 0.87058824, 0.89803922], ...
    'fill', [0.91764706, 0.94117647, 0.95686275], ...
    'background', [1.00000000, 1.00000000, 1.00000000], ...
    ...
    'blue', [0.32156863, 0.57254902, 0.96862745], ...
    'orange', [0.96862745, 0.63529412, 0.30980392], ...
    'teal', [0.30588235, 0.65098039, 0.37647059], ...
    'gray', [0.47450980, 0.79215686, 0.98431373], ...
    'lightGray', [0.85098039, 0.87058824, 0.89803922]);
style.categoricalOrder = [ ...
    0.80000000, 0.14117647, 0.48627451; ...
    0.91372549, 0.32549020, 0.31764706; ...
    0.96862745, 0.63529412, 0.30980392; ...
    0.98431373, 0.92156863, 0.40000000; ...
    0.30588235, 0.65098039, 0.37647059; ...
    0.47450980, 0.79215686, 0.98431373; ...
    0.32156863, 0.57254902, 0.96862745; ...
    0.66666667, 0.46666667, 0.91372549];
style.lineWidth = 1.6;
style.markerSize = 5.2;
style.fontName = char(parser.Results.FontName);
style.fontSize = parser.Results.FontSize;
style.textColor = style.palette.ink;

axesList = ax(:);
for index = 1:numel(axesList)
    currentAxes = axesList(index);
    set(currentAxes, ...
        'FontName', style.fontName, ...
        'FontSize', style.fontSize, ...
        'LineWidth', 0.8, ...
        'TickDir', 'out', ...
        'TickLength', [0.015, 0.015], ...
        'Box', 'off', ...
        'Layer', 'top', ...
        'Color', style.palette.background, ...
        'XColor', style.textColor, ...
        'YColor', style.textColor, ...
        'XGrid', 'on', ...
        'YGrid', 'on', ...
        'GridColor', style.palette.grid, ...
        'GridAlpha', 0.45, ...
        'MinorGridAlpha', 0.25, ...
        'ColorMode', 'manual', ...
        'XColorMode', 'manual', ...
        'YColorMode', 'manual', ...
        'GridColorMode', 'manual');
    currentAxes.TitleFontSizeMultiplier = 1.06;
    currentAxes.LabelFontSizeMultiplier = 1.0;
    currentAxes.Title.Color = style.textColor;
    currentAxes.XLabel.Color = style.textColor;
    currentAxes.YLabel.Color = style.textColor;
    colororder(currentAxes, style.categoricalOrder);
end
end
