function fig = mf_publication_figure(S, heightCm)
% Create a hidden canvas at the declared final physical size.
if nargin < 2
    heightCm = S.heightCm;
end
fig = figure('Visible', 'off', 'Color', S.colors.background, ...
    'InvertHardcopy', 'off', ...
    'Units', 'centimeters', 'Position', [2, 2, S.widthCm, heightCm], ...
    'PaperUnits', 'centimeters', 'PaperSize', [S.widthCm, heightCm], ...
    'PaperPosition', [0, 0, S.widthCm, heightCm], ...
    'PaperPositionMode', 'manual');
set(fig, 'DefaultAxesFontName', S.fontName, ...
    'DefaultAxesFontSize', S.fontSize, ...
    'DefaultTextFontName', S.fontName, ...
    'DefaultTextFontSize', S.fontSize);
end
