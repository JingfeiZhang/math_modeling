function outputs = fig_q1_blind_forecast_interval(D, outputDir, S)
fig = mf_publication_figure(S);
ax = axes(fig, 'Position', [0.13, 0.17, 0.82, 0.70]);
x = double(D.relativeHour(:)) + 0.5;
hold(ax, 'on');
patch(ax, [x; flipud(x)], [D.lower95(:); flipud(D.upper95(:))], ...
    S.colors.primary, 'FaceAlpha', S.bandAlpha, 'EdgeColor', 'none', ...
    'DisplayName', 'Summed marginal 95% bounds');
plot(ax, x, D.actual, '-', 'Color', S.colors.ink, 'LineWidth', S.lineWidth, ...
    'Marker', 'o', 'MarkerSize', S.markerSize, 'MarkerIndices', 1:4:numel(x), ...
    'DisplayName', 'Observed');
plot(ax, x, D.baseline, '--', 'Color', S.colors.baseline, 'LineWidth', S.lineWidth, ...
    'Marker', 's', 'MarkerSize', S.markerSize, 'MarkerIndices', 2:4:numel(x), ...
    'DisplayName', 'Seasonal baseline');
plot(ax, x, D.main, '-', 'Color', S.colors.primary, 'LineWidth', S.lineWidth, ...
    'Marker', '^', 'MarkerSize', S.markerSize, 'MarkerIndices', 3:4:numel(x), ...
    'DisplayName', 'HGBR + reconciliation');
hold(ax, 'off');
mf_apply_axes(ax, S);
xlim(ax, [0, 24]);
ax.XTick = 0:6:24;
xlabel(ax, 'Elapsed hour in blind-test window');
ylabel(ax, 'System workload (GPU h)');
mf_legend(ax, S, 'Location', 'northoutside', 'Orientation', 'horizontal', ...
    'NumColumns', 2);
outputs = mf_export_triplet(fig, outputDir, "fig-q1-blind-forecast-interval", S);
close(fig);
end
